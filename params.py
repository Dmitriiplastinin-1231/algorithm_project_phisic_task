"""
Параметры задачи «Запуск с морской платформы».

Модель динамики:
    θ'' + a·θ(t−τ) = 0,   a = k/I
    ÿ_lat = g_lat · θ(t)

Начальные условия (качка платформы):
    θ(0) = A·cos(φ₀),  θ'(0) = −A·Ω·sin(φ₀),  Ω = 2π/T
"""

import math
import argparse


# ── Физические параметры ──────────────────────────────────────────────────
g        = 9.81       # м/с²  ускорение свободного падения

# Вертикальная траектория ракеты (упрощённая: постоянное ускорение)
a_z_net  = 10.0       # м/с²  среднее вертикальное ускорение (тяга − g)
# Высота:  H(t) = ½·a_z_net·t²

# Боковая динамика: ÿ_lat = g_lat·θ  (малые углы, тяга ≈ 1.5 g)
g_lat    = 14.7       # м/с²  ≈ 1.5·g

# ── Параметры платформы ───────────────────────────────────────────────────
A        = 0.05       # рад   амплитуда качки (~2.86°)
T_rock   = 8.0        # с     период качки
Omega    = 2 * math.pi / T_rock   # рад/с  угловая частота

# ── Система управления (TVC) ──────────────────────────────────────────────
tau      = 0.3        # с     задержка контура ОС (сенсор + вычисления + привод)
a_ctrl   = 0.05       # рад/с²/рад  a = k/I  (жёсткость пропорционального регулятора)
# Замечание: ДДУ θ''+aθ(t−τ)=0 неустойчиво при любых a>0,τ>0;
# при a=0.05 рост медленный (|θ|/A ~ 1.4 за 45 с, ~3.5 за 179 с).

# ── Параметры численного интегрирования ──────────────────────────────────
h_step   = 0.01       # с     шаг по времени (dt)

# ── Высоты для анализа ────────────────────────────────────────────────────
H_10km   = 10_000.0   # м   Задача 1
H_160km  = 160_000.0  # м   Задача 2 (вывод на орбиту)

# ── Фазовый перебор ───────────────────────────────────────────────────────
N_phases_small = 8    # базовый перебор (N ≥ 8 — инженерная оценка)
N_phases_large = 72   # расширенный перебор для верификации

# ── Линеаризация: коэффициент усиления K ─────────────────────────────────
# ΔU(t) = −K · ΔV(t−τ),  ΔV = [y, ẏ, θ, θ̇]
# TVC воздействует только на угловое ускорение (B = [0,0,0,1]ᵀ)
# Компонента K[2] = a_ctrl — пропорциональный закон по углу
K_gain   = [0.0, 0.0, a_ctrl, 0.0]


# ── Вспомогательные функции ───────────────────────────────────────────────
def height_at(t):
    """Высота ракеты в момент t при постоянном вертикальном ускорении."""
    return 0.5 * a_z_net * t * t


def time_to_height(H):
    """Время достижения высоты H (с)."""
    return math.sqrt(2.0 * H / a_z_net)


def parse_args(description: str) -> argparse.Namespace:
    """Общий парсер аргументов командной строки для всех скриптов."""
    p = argparse.ArgumentParser(description=description)
    p.add_argument('--A',     type=float, default=A,       help=f'Амплитуда качки, рад (по умолчанию {A})')
    p.add_argument('--tau',   type=float, default=tau,     help=f'Задержка τ, с (по умолчанию {tau})')
    p.add_argument('--T',     type=float, default=T_rock,  help=f'Период качки, с (по умолчанию {T_rock})')
    p.add_argument('--h',     type=float, default=h_step,  help=f'Шаг интегрирования, с (по умолчанию {h_step})')
    p.add_argument('--a',     type=float, default=a_ctrl,  help=f'Коэффициент a=k/I (по умолчанию {a_ctrl})')
    return p.parse_args()
